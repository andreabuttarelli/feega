create view public.org_credits_at_risk with (security_invoker=false) as  WITH grants AS (
         SELECT credit_ledger.org_id,
            credit_ledger.amount,
            credit_ledger.expires_at,
            sum(credit_ledger.amount) OVER (PARTITION BY credit_ledger.org_id ORDER BY credit_ledger.expires_at, credit_ledger.created_at) AS running_total
           FROM credit_ledger
          WHERE ((credit_ledger.kind = 'grant'::text) AND ((credit_ledger.expires_at IS NULL) OR (credit_ledger.expires_at > now())))
        )
 SELECT org_id,
    sum(amount) FILTER (WHERE (expires_at IS NOT NULL)) AS expiring_credits,
    min(expires_at) FILTER (WHERE (expires_at IS NOT NULL)) AS next_expiry
   FROM grants
  GROUP BY org_id;
